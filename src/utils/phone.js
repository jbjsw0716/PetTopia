// F-38 연락처 형식 검사와 정규화.
//
// 배송 정보와 프로필이 같은 규칙을 쓴다. 판정이 갈리면 프로필에서 저장한 값이
// 배송 정보 기본값으로 들어갔을 때 곧바로 오류가 난다. 그래서 한 곳에 둔다.
//
// 검사는 하이픈을 빼고, 저장은 하이픈을 넣는다.
// 가이드 샘플은 01000000000 으로 하이픈 없이 저장하지만 우리는 다르다.
//
// 이 함수는 새 입력에만 쓴다. 이미 저장된 기록을 이 규칙으로 다시 판정하지 않는다
// (나중에 검사를 붙였다는 이유로 과거 연락처를 지우지 않는다).
// storage.js 의 주문 구조 검사가 연락처 형식을 보지 않는 이유가 이것이다.

// 통과하면 010-0000-0000 모양의 문자열을, 어긋나면 null 을 돌려준다.
// 빈 값을 따로 구분하지 않는다 — 빈 값은 필수 값 검사가 먼저 잡는다.
// 같은 자리에 두 문구를 함께 띄우지 않기 위해서다.
function normalizePhone(value) {
  const digits = value.trim().replace(/-/g, '');

  if (!/^010[0-9]{8}$/.test(digits)) {
    return null;
  }

  return digits.slice(0, 3) + '-' + digits.slice(3, 7) + '-' + digits.slice(7);
}

export { normalizePhone };
